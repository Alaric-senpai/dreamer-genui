#!/usr/bin/env node
/**
 * Generate the "Customization Surface" docs (AGENTS.md §8.5) from the
 * component metadata registry.
 *
 * Run with `pnpm dg:component-docs`. Writes one file per component to
 * `docs/components/<name>.md` plus an index. Node's built-in type stripping
 * lets us import the TypeScript metadata module directly (Node >= 23).
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'docs', 'components');

const { COMPONENT_REGISTRY } = await import(
  join(root, 'packages/dreamer-genui/src/react/anatomy-meta.ts')
);

const names = Object.keys(COMPONENT_REGISTRY).sort();

function renderComponent(name, meta) {
  const partRows = meta.parts
    .map((part) => `| \`${part}\` | \`${name}\` | \`dg-${name}-${part}\` |`)
    .join('\n');

  const tokens = meta.tokens.length
    ? meta.tokens.map((token) => `- \`${token}\``).join('\n')
    : '_No component-level tokens; inherits the board theme._';

  const variants = meta.variants.length
    ? meta.variants.map((variant) => `- \`${variant}\``).join('\n')
    : '_None._';

  const dataAttrs = meta.dataAttrs.length
    ? meta.dataAttrs.map((attr) => `- \`${attr}\``).join('\n')
    : '_None._';

  const events = meta.events.length
    ? meta.events.map((event) => `- \`${event}\``).join('\n')
    : '_None._';

  const effects = meta.effects.length
    ? meta.effects.map((effect) => `- \`${effect}\``).join('\n')
    : '_None._';

  return `# \`${name}\`

> Generated by \`pnpm dg:component-docs\` from \`src/react/anatomy-meta.ts\`. Do not edit by hand.

## Parts

| Part | \`data-dg-part\` | Stable class | Reference class |
| :--- | :--- | :--- | :--- |
${partRows}

Every part is addressable through \`partClassNames\` / \`partStyles\`:

\`\`\`tsx
<Board
  store={board}
  partClassNames={{ ${name}: { ${meta.parts[0] ?? 'root'}: 'my-${name}' } }}
/>
\`\`\`

## Component tokens

${tokens}

## Variants

${variants}

## Data attributes

${dataAttrs}

## Events

${events}

## Effects

${effects}

## Replacing the component

Register an override on the provider (the override receives the default
rendering so it can decorate rather than reimplement):

\`\`\`tsx
<DreamerProvider
  registry={registry}
  components={{
    ${name}: ({ renderDefault }) => (
      <div data-custom-${name}>{renderDefault()}</div>
    ),
  }}
>
  <Board store={board} />
</DreamerProvider>
\`\`\`

The default renderer stays accessible through \`renderDefault()\`, and the
override owns the wrapper markup. The component is still styled through the
same \`--dg-*\` tokens.
`;
}

await mkdir(outDir, { recursive: true });

for (const name of names) {
  await writeFile(join(outDir, `${name}.md`), renderComponent(name, COMPONENT_REGISTRY[name]), 'utf8');
}

const index = `# Component customization surfaces

> Generated by \`pnpm dg:component-docs\` from \`src/react/anatomy-meta.ts\`.

| Component | Parts | Override key |
| :--- | :--- | :--- |
${names
  .map(
    (name) =>
      `| [\`${name}\`](./${name}.md) | ${COMPONENT_REGISTRY[name].parts
        .map((part) => `\`${part}\``)
        .join(', ')} | \`components={{ ${name}: … }}\` |`,
  )
  .join('\n')}
`;

await writeFile(join(outDir, 'README.md'), index, 'utf8');
console.log(`Wrote ${names.length} component pages to docs/components/`);
